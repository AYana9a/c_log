/**
 * メッセージ配列から各心理機能の生スコアを計算する。
 * @param {string[]} messages
 * @returns {Record<string, number>} 機能ごとの正規化前スコア(メッセージ数で割った密度)
 */
export function scoreFunctions(messages) {
  const raw = Object.fromEntries(FUNCTIONS.map((f) => [f, 0]));
  if (!messages.length) return raw;

  // メッセージの長さ・「!」「?」の頻度といった文体の統計は、以前は
  // 「短文が多い→Se」「長文が多い→Si」のように加点材料として使っていたが、
  // これは実質「LINE/Discordで短い相槌を連投しがちか」「たまたま長い説明を
  // した話題があったか」を測っているだけで、心理機能とは別の要因(媒体の
  // 作法・その日の話題)に左右されやすい。何を"言っているか"だけで判断する
  // ため、こうした文体統計による加点は行わない。
  for (const text of messages) {
    for (const fn of FUNCTIONS) {
      for (const [pattern, weight] of KEYWORDS[fn]) {
        if (text.includes(pattern)) {
          raw[fn] += weight;
        }
      }
    }
  }

  const n = messages.length;
  // メッセージ数で割って「1メッセージあたりの密度」にする
  for (const fn of FUNCTIONS) {
    raw[fn] = raw[fn] / n;
  }
  return raw;
}

/**
 * 生スコアを 0-100 の範囲に min-max 正規化する(レーダーチャート表示用)。
 * 8機能の相対的な強弱を見るためのものであり、絶対値に意味はない。
 */
export function normalizeScores(raw) {
  const values = FUNCTIONS.map((f) => raw[f]);
  const min = Math.min(...values);
  const max = Math.max(...values);
  const range = max - min || 1;
  const normalized = {};
  for (const fn of FUNCTIONS) {
    normalized[fn] = Math.round(((raw[fn] - min) / range) * 90 + 10); // 10-100の範囲で見やすく
  }
  return normalized;
}
